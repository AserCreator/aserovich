    {
        _consoleEntity = consoleEntity;
    }

    protected override void KeyBindUp(GUIBoundKeyEventArgs args)
    {
        base.KeyBindUp(args);

        if (_coordinates == null || _rotation == null || args.Function != EngineKeyFunctions.UIClick ||
            OnRadarClick == null)
        {
            return;
        }

        var a = InverseScalePosition(args.RelativePosition);
        var relativeWorldPos = new Vector2(a.X, -a.Y);
        relativeWorldPos = _rotation.Value.RotateVec(relativeWorldPos);
        var coords = _coordinates.Value.Offset(relativeWorldPos);
        OnRadarClick?.Invoke(coords);
    }

    /// <summary>
    /// Gets the entitycoordinates of where the mouseposition is, relative to the control.
    /// </summary>
    [PublicAPI]
    public EntityCoordinates GetMouseCoordinates(ScreenCoordinates screen)
    {
        if (_coordinates == null || _rotation == null)
        {
            return EntityCoordinates.Invalid;
        }

        var pos = screen.Position / UIScale - GlobalPosition;

        var a = InverseScalePosition(pos);
        var relativeWorldPos = new Vector2(a.X, -a.Y);
        relativeWorldPos = _rotation.Value.RotateVec(relativeWorldPos);
        var coords = _coordinates.Value.Offset(relativeWorldPos);
        return coords;
    }

    public void UpdateState(NavInterfaceState state)
    {
        SetMatrix(EntManager.GetCoordinates(state.Coordinates), state.Angle);

        WorldMaxRange = state.MaxRange;

        if (WorldMaxRange < WorldRange)
        {
            ActualRadarRange = WorldMaxRange;
        }

        if (WorldMaxRange < WorldMinRange)
            WorldMinRange = WorldMaxRange;

        ActualRadarRange = Math.Clamp(ActualRadarRange, WorldMinRange, WorldMaxRange);

        RotateWithEntity = state.RotateWithEntity;

        _docks = state.Docks;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        DrawBacking(handle);
        DrawCircles(handle);

        // No data
        if (_coordinates == null || _rotation == null)
        {
            return;
        }

        var xformQuery = EntManager.GetEntityQuery<TransformComponent>();
        var fixturesQuery = EntManager.GetEntityQuery<FixturesComponent>();
        var bodyQuery = EntManager.GetEntityQuery<PhysicsComponent>();

        if (!xformQuery.TryGetComponent(_coordinates.Value.EntityId, out var xform)
            || xform.MapID == MapId.Nullspace)
        {
            return;
        }

        var mapPos = _transform.ToMapCoordinates(_coordinates.Value);
        var posMatrix = Matrix3Helpers.CreateTransform(_coordinates.Value.Position, _rotation.Value);
        var ourEntRot = RotateWithEntity ? _transform.GetWorldRotation(xform) : _rotation.Value;
        var ourEntMatrix = Matrix3Helpers.CreateTransform(_transform.GetWorldPosition(xform), ourEntRot);
        var shuttleToWorld = Matrix3x2.Multiply(posMatrix, ourEntMatrix);
        Matrix3x2.Invert(shuttleToWorld, out var worldToShuttle);
        var shuttleToView = Matrix3x2.CreateScale(new Vector2(MinimapScale, -MinimapScale)) * Matrix3x2.CreateTranslation(MidPointVector);

        // Draw our grid in detail
        var ourGridId = xform.GridUid;
        if (EntManager.TryGetComponent<MapGridComponent>(ourGridId, out var ourGrid) &&
            fixturesQuery.HasComponent(ourGridId.Value))
        {
            var ourGridToWorld = _transform.GetWorldMatrix(ourGridId.Value);
            var ourGridToShuttle = Matrix3x2.Multiply(ourGridToWorld, worldToShuttle);
            var ourGridToView = ourGridToShuttle * shuttleToView;
            var color = _shuttles.GetIFFColor(ourGridId.Value, self: true);

            DrawGrid(handle, ourGridToView, (ourGridId.Value, ourGrid), color);
            DrawDocks(handle, ourGridId.Value, ourGridToView);
            DrawOrbit(handle, worldToShuttle * shuttleToView, ourGridId.Value);
            //DrawOrbit(handle, worldToShuttle * shuttleToView, ourGridId.Value);
        }

        // Draw radar position on the station
        const float radarVertRadius = 2f;
        var radarPosVerts = new Vector2[]
        {
            ScalePosition(new Vector2(0f, -radarVertRadius)),
            ScalePosition(new Vector2(radarVertRadius / 2f, 0f)),
            ScalePosition(new Vector2(0f, radarVertRadius)),
            ScalePosition(new Vector2(radarVertRadius / -2f, 0f)),
        };

        handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, radarPosVerts, Color.Lime);

        var rot = ourEntRot + _rotation.Value;
        var viewBounds = new Box2Rotated(new Box2(-WorldRange, -WorldRange, WorldRange, WorldRange).Translated(mapPos.Position), rot, mapPos.Position);
        var viewAABB = viewBounds.CalcBoundingBox();

        _grids.Clear();
        _maps.FindGridsIntersecting(xform.MapID, new Box2(mapPos.Position - MaxRadarRangeVector, mapPos.Position + MaxRadarRangeVector), ref _grids, approx: true, includeMap: false);

        // Draw other grids... differently
        foreach (var grid in _grids)
        {
            var gUid = grid.Owner;
            if (gUid == ourGridId || !fixturesQuery.HasComponent(gUid))
                continue;

            var gridBody = bodyQuery.GetComponent(gUid);
            EntManager.TryGetComponent<IFFComponent>(gUid, out var iff);

            if (!_shuttles.CanDraw(gUid, gridBody, iff))
                continue;

            var curGridToWorld = _transform.GetWorldMatrix(gUid);
            var curGridToView = curGridToWorld * worldToShuttle * shuttleToView;

            var labelColor = _shuttles.GetIFFColor(grid, self: false, iff);
            var coordColor = new Color(labelColor.R * 0.8f, labelColor.G * 0.8f, labelColor.B * 0.8f, 0.5f);

            // Others default:
            // Color.FromHex("#FFC000FF")
            // Hostile default: Color.Firebrick
            var labelName = _shuttles.GetIFFLabel(grid, self: false, iff);

            if (ShowIFF &&
                 labelName != null)
            {
                var gridBounds = grid.Comp.LocalAABB;

                // Display the coordinates of the center of the grid and its distance from the console.
                var gridCentre = Vector2.Transform(gridBody.LocalCenter, curGridToView);
                var gridCenterMapPos = _transform.ToWorldPosition(new EntityCoordinates(gUid, gridBody.LocalCenter));

                var gridDistance = (gridCenterMapPos - mapPos.Position).Length();
                var labelText = Loc.GetString("shuttle-console-iff-label", ("name", labelName),
                    ("distance", $"{gridDistance:0.0}"));
                var coordsText = $"({gridCenterMapPos.X:0.0}, {gridCenterMapPos.Y:0.0})";

                // yes 1.0 scale is intended here.
                var labelDimensions = handle.GetDimensions(Font, labelText, 1f);
                var coordsDimensions = handle.GetDimensions(Font, coordsText, 0.7f);

                // y-offset the control to always render below the grid (vertically)
                var yOffset = Math.Max(gridBounds.Height, gridBounds.Width) * MinimapScale / 1.8f;

                // The actual position in the UI.
                var gridScaledPosition = gridCentre - new Vector2(0, -yOffset);

                // Normalize the grid position if it exceeds the viewport bounds
                // normalizing it instead of clamping it preserves the direction of the vector and prevents corner-hugging
                var gridOffset = gridScaledPosition / PixelSize - new Vector2(0.5f, 0.5f);
                var offsetMax = Math.Max(Math.Abs(gridOffset.X), Math.Abs(gridOffset.Y)) * 2f;
                if (offsetMax > 1)
                {
                    gridOffset = new Vector2(gridOffset.X / offsetMax, gridOffset.Y / offsetMax);

                    gridScaledPosition = (gridOffset + new Vector2(0.5f, 0.5f)) * PixelSize;
                }

                var labelUiPosition = gridScaledPosition - new Vector2(labelDimensions.X / 2f, 0);
                var coordUiPosition = gridScaledPosition - new Vector2(coordsDimensions.X / 2f, -labelDimensions.Y);

                // clamp the IFF label's UI position to within the viewport extents so it hugs the edges of the viewport
                // coord label intentionally isn't clamped so we don't get ugly clutter at the edges
                var controlExtents = PixelSize - new Vector2(labelDimensions.X, labelDimensions.Y); //new Vector2(labelDimensions.X * 2f, labelDimensions.Y);
                labelUiPosition = Vector2.Clamp(labelUiPosition, Vector2.Zero, controlExtents);

                // draw IFF label
                handle.DrawString(Font, labelUiPosition, labelText, labelColor);

                // only draw coords label if close enough
                if (offsetMax < 1)
                {
                    handle.DrawString(Font, coordUiPosition, coordsText, 0.7f, coordColor);
                }
            }

            // Detailed view
            var gridAABB = curGridToWorld.TransformBox(grid.Comp.LocalAABB);

            // Skip drawing if it's out of range.
            if (!gridAABB.Intersects(viewAABB))
                continue;

            DrawGrid(handle, curGridToView, grid, labelColor);
            DrawDocks(handle, gUid, curGridToView);
        }

        // If we've set the controlling console, and it's on a different grid
        // to the shuttle itself, then draw an additional marker to help the
        // player determine where they are relative to the shuttle.
        if (_consoleEntity != null && xformQuery.TryGetComponent(_consoleEntity, out var consoleXform))
        {
            if (consoleXform.ParentUid != _coordinates.Value.EntityId)
            {
                var consolePositionWorld = _transform.GetWorldPosition((EntityUid)_consoleEntity);
                var p = Vector2.Transform(consolePositionWorld, worldToShuttle * shuttleToView);
                handle.DrawCircle(p, 5, Color.ToSrgb(Color.Cyan), true);
            }
        }

    }

    /// <summary>
    /// Draws the docking ports: Cargo, Arrivals and General(ShowDocks) on the radar. This is a separate method to avoid cluttering the main Draw method.
    /// </summary>
    private void DrawDocks(DrawingHandleScreen handle, EntityUid uid, Matrix3x2 gridToView)
    {
        if (!ShowDocks && !ShowCargoDocks && !ShowArrivalDocks)
            return;

        const float dockScale = 0.6f;
        var topLeft = new Vector2(-dockScale, -dockScale);
        var topRight = new Vector2(dockScale, -dockScale);
        var bottomRight = new Vector2(dockScale, dockScale);
        var bottomLeft = new Vector2(-dockScale, dockScale);

        var nent = EntManager.GetNetEntity(uid);

        const float sqrt2 = 1.41421356f;
        const float dockRadius = dockScale * sqrt2;
        // Worst-case bounds used to cull a dock:
        Box2 viewBounds = new Box2(
            -dockRadius * UIScale,
            -dockRadius * UIScale,
            (Size.X + dockRadius) * UIScale,
            (Size.Y + dockRadius) * UIScale);

        if (_docks.TryGetValue(nent, out var docks))
        {
            Span<Vector2> verts = new Vector2[4];
            foreach (var state in docks)
            {
                var position = state.Coordinates.Position;

                var positionInView = Vector2.Transform(position, gridToView);
                if (!viewBounds.Contains(positionInView))
                {
                    continue;
                }

                var color = Color.ToSrgb(state.HighlightedColor);

                verts[0] = Vector2.Transform(position + topLeft, gridToView);
                verts[1] = Vector2.Transform(position + topRight, gridToView);
                verts[2] = Vector2.Transform(position + bottomRight, gridToView);
                verts[3] = Vector2.Transform(position + bottomLeft, gridToView);

                switch (state.Category)
                {
                    case LegendCategory.Cargo when !ShowCargoDocks:
                    case LegendCategory.Arrivals when !ShowArrivalDocks:
                    case LegendCategory.General when !ShowDocks:
                        continue;
                }

                if (state.GridDockedWith == null)
                    handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, verts, color.WithAlpha(0.8f));
                else
                    handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, verts, color.WithAlpha(0.2f));
                handle.DrawPrimitives(DrawPrimitiveTopology.LineStrip, verts, color);
            }
        }
    }
    public double getLen(Vector2 vec)
    {
        return Math.Sqrt(vec.X*vec.X + vec.Y*vec.Y);
    }
    private Vector2 GetRelative(OrbitalGravityComponent grav, TransformComponent xform, PhysicsComponent body)
    {
        var com = Vector2.Transform(body.LocalCenter, _transform.GetWorldMatrix(xform));
        return new Vector2(com.X - grav.Center.X, com.Y - grav.Center.Y);
    }

    private Vector2 GetRelativePos(OrbitalGravityComponent grav, TransformComponent xform, Vector2 position)
    {
        var com = Vector2.Transform(position, _transform.GetWorldMatrix(xform));
        return new Vector2(com.X - grav.Center.X, com.Y - grav.Center.Y);
    }


    private void DrawOrbit(DrawingHandleScreen handle, Matrix3x2 worldToView, EntityUid gridUid)
    {
        if (!EntManager.TryGetComponent(gridUid, out TransformComponent? xform) ||
            !EntManager.TryGetComponent(gridUid, out PhysicsComponent? body) ||
            !EntManager.TryGetComponent(gridUid, out OrbitalBodyComponent? orbital) ||
            xform.MapUid is not { } map ||
            !EntManager.TryGetComponent(map, out OrbitalGravityComponent? grav))
        {
            return;
        }

        //OrbitData orbit = new OrbitData(orbital.Mu, orbital.P, orbital.Ecc, orbital.Omega, orbital.Dir);
        var center = new Vector2((float) grav.Center.X, (float) grav.Center.Y);
        var color = Color.Cyan.WithAlpha(0.7f);

        const int segments = 5000;
        //const double maxRadius = 20000;

        Vector2 bodyPos = xform.WorldPosition;
        Vector2 prev = Vector2.Transform(bodyPos, worldToView);
        //Vector2 offset = new Vector2(0,0);
        float dt = (float)_timing.TickPeriod.TotalSeconds;
        Vector2 linearVelocity = body.LinearVelocity;
        float speedMult = 1;
        Vector2? apoapsis = null;
        Vector2? pereapsis = null;
        bool pass = false;
        for (var i = 0; i <= segments; i++)
        {
            Vector2 r = bodyPos - grav.Center;
            double dist = getLen(r);

            linearVelocity += -(r.Normalized()) * (float)((grav.Mass*(float)grav.G)/(dist*dist)) * (1/body.Mass)*dt * speedMult;

            bodyPos += linearVelocity * dt * speedMult;

            double resDist = Vector2.Distance(grav.Center, bodyPos);
            if (apoapsis == null || Vector2.Distance(grav.Center, apoapsis.Value) < resDist)
            {
                apoapsis = bodyPos;
            }
            if (pereapsis == null || Vector2.Distance(grav.Center, pereapsis.Value) > resDist)
            {
                pereapsis = bodyPos;
            }

            var world = bodyPos;// + (-new Vector2((float)r.X,(float)r.Y)*(float)(grav.Mu * body.Mass / (len * len)));//center + new Vector2((float) p.X, (float) p.Y);
            var screen = Vector2.Transform(world, worldToView);

            //if (prev != null)
            handle.DrawLine(prev, screen, color);
            speedMult = 1;//1/Vector2.Distance(prev,screen);
            prev = screen;
            if(pass && Vector2.Distance(bodyPos, xform.WorldPosition) < 1)
            {
                handle.DrawLine(Vector2.Transform(xform.WorldPosition, worldToView), screen, color);
                break;
            }
            if(Vector2.Distance(bodyPos, xform.WorldPosition) > 1)
            {
                pass = true;
            }

        }
        handle.DrawCircle(Vector2.Transform(xform.WorldPosition, worldToView), 4f, Color.Yellow);
        handle.DrawCircle(Vector2.Transform(center, worldToView), 10f, Color.Yellow);

        if (apoapsis == null || pereapsis == null) return;
        handle.DrawCircle(Vector2.Transform(apoapsis.Value, worldToView), 4f, color);
        handle.DrawString(Font, Vector2.Transform(apoapsis.Value, worldToView) + new Vector2(8f, -8f), "Апоапсис "+Vector2.Distance(grav.Center, apoapsis.Value), color);

        handle.DrawCircle(Vector2.Transform(pereapsis.Value, worldToView), 4f, color);
        handle.DrawString(Font, Vector2.Transform(pereapsis.Value, worldToView) + new Vector2(8f, -8f), "Переапсис "+Vector2.Distance(grav.Center, pereapsis.Value), color);
    }

    private Vector2 InverseScalePosition(Vector2 value)
    {
        return (value - MidPointVector) / MinimapScale;
    }
